"""Human-readable routing summary for the 10 story patients (story_patient=true) -> data/raw/routing/story_patients.md.

Reads only local outputs: data/processed/synthetic/{patients,questionnaire,contacts_routed,cooling_match}.csv
and data/raw/routing/{contacts_summary,cooling_summary}.json. No network calls.
Run after routing_contacts.py and routing_cooling.py:
    ~/.local/bin/uv run python scripts/routing_story.py
"""
import json, os
from routing_common import RAW, read_csv

MODE = {"walk": "walking (older-adult pace)", "drive": "driving (free-flow)", "transit_approx": "subway (approx.)"}


def yn(b):
    return "yes" if b == "true" else "no"


def main():
    pts = [p for p in read_csv("patients.csv") if p["story_patient"] == "true"]
    q = {r["patient_id"]: r for r in read_csv("questionnaire.csv")}
    con = read_csv("contacts_routed.csv")
    cool = read_csv("cooling_match.csv")
    cs = json.load(open(os.path.join(RAW, "contacts_summary.json")))
    ks = json.load(open(os.path.join(RAW, "cooling_summary.json")))
    eng = cs["routing_engine"]
    L = ["# Story patients: routing results (SYNTHETIC)", "",
         "Every person here is synthetic (data/processed/synthetic). Generated by `scripts/routing_story.py` from",
         "`contacts_routed.csv` and `cooling_match.csv`. Routing engine: "
         + ("OpenRouteService" if eng == "ors" else "public OSRM (FOSSGIS, routing.openstreetmap.de; OpenStreetMap network)")
         + "; see README.md in this folder for methods and caveats.", "",
         f"- Contact rule (spec §4.4a): travel <= T_max - 15 min (patient p90) - 15 min (contact p90). "
         "Travel allowance = 15 / 30 / 60 min for the 45 / 60 / 90 min budgets.",
         "- Walking uses an older-adult pace (0.8 m/s) on the routed distance. Driving is free-flow (no traffic, "
         "no parking), so it is optimistic; \"no car\" = walking or subway only.",
         "- Subway times are an approximation (straight line between nearest stations), not GTFS routing.",
         f"- Cooling places: reference heat day {ks['ref_day']} ({ks['ref_weekday']}, peak heat index "
         f"{ks['ref_day_max_heat_index_f']} F in the replay). Leave-by = arrive before 11 AM.", ""]
    for p in pts:
        pid = p["patient_id"]
        qq = q[pid]
        L += [f"## {pid}: {p['story_label']}", "",
              f"{p['age']}{p['sex'][0].upper()}, ZIP {p['zip']}, language {p['preferred_language']}. "
              f"Step-free needed: {yn(qq['mobility_step_free_needed'])}. Can reach a cool place: {qq['q5_can_reach_cool_place']}. "
              f"Lives alone: {yn(qq['q4_lives_alone'])}. Working AC: {qq['q1_working_ac']}.", ""]
        cc = [c for c in con if c["patient_id"] == pid]
        if not cc:
            L += ["**Trusted contact:** none on file -> buddy match + priority call list.", ""]
        else:
            L += ["**Trusted contacts** (routed travel to the patient's door):", "",
                  "| Contact | Where | Walk | Drive | Subway (approx.) | Fastest | Qualifies 45 / 60 / 90 (any mode) | No car | Naive placeholder |",
                  "|---|---|---|---|---|---|---|---|---|"]
            for c in cc:
                def m(v):
                    return f"{float(v):.0f} min" if v not in ("", None) else "n/a"
                q_any = " / ".join(yn(c[f"qualifies_{b}"]) for b in (45, 60, 90))
                q_nc = " / ".join(yn(c[f"qualifies_nocar_{b}"]) for b in (45, 60, 90))
                q_nv = " / ".join(yn(c[f"naive_qualifies_{b}min_derived"]) for b in (45, 60, 90))
                L.append(f"| {c['relationship'].replace('_', ' ')} | {c['location_type'].replace('_', ' ')}, "
                         f"{float(c['straight_line_km']):.1f} km | {m(c['walk_older_pace_min'])} | {m(c['drive_ors_min'])} | "
                         f"{m(c['transit_approx_min'])} | {MODE.get(c['fastest_mode'], c['fastest_mode'])} {m(c['fastest_min'])} | "
                         f"{q_any} | {q_nc} | {c['naive_travel_mode']} {float(c['naive_travel_min']):.0f} min: {q_nv} |")
            any_q = {b: any(c[f"qualifies_{b}"] == "true" for c in cc) for b in (45, 60, 90)}
            nc_q = {b: any(c[f"qualifies_nocar_{b}"] == "true" for c in cc) for b in (45, 60, 90)}
            L.append("")
            if not any(any_q.values()):
                L.append("**Verdict:** no contact qualifies at any budget -> ask for a closer contact or a buddy, plus priority call list.")
            else:
                L.append("**Verdict:** has a qualifying contact at " + ", ".join(f"{b} min" for b in any_q if any_q[b])
                         + " if the contact drives; without a car: "
                         + (", ".join(f"{b} min" for b in nc_q if nc_q[b]) or "none") + ".")
            notes = sorted({n for c in cc for n in c["routing_note"].split("; ") if n})
            if notes:
                L.append("Notes: " + "; ".join(notes) + ".")
            L.append("")
        L += ["**Morning cooling-place text options** (nearest 3 by walking time):", "",
              "| # | Place | Type | Walk | Step-free | Hours that day | Leave by |", "|---|---|---|---|---|---|---|"]
        for r in [r for r in cool if r["patient_id"] == pid]:
            hrs = (f"{r['opens_ref_day']}-{r['closes_ref_day']}" if r["opens_ref_day"] else "unknown")
            addr = f", {r['address']}" if r["address"] else ""
            L.append(f"| {r['rank']} | {r['place_name']}{addr} | {r['place_type']} | {float(r['walk_min']):.0f} min "
                     f"({r['walk_pace'].split(' (')[0]}) | {r['step_free_status']} | {hrs} | {r['leave_by']} |")
        top = [r for r in cool if r["patient_id"] == pid and r["rank"] == "1"][0]
        L += ["", f"Draft text: \"{top['text_line']}\"", ""]
        n = sorted({x for r in cool if r["patient_id"] == pid for x in r["notes"].split("; ") if x})
        if n:
            L += ["Notes: " + "; ".join(n) + ".", ""]
    with open(os.path.join(RAW, "story_patients.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
